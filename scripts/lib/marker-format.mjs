/*
 * 変異対照の「目印」の形。**ここ1か所だけ**に置く（第26回監査 R26-001）。
 *
 * ランナー（作る側）と検証器（読む側）が別々に形を持つと、片方を緩めても
 * もう片方が黙って通る。境界は1つにする。
 *
 *   GXS_MARK.<名前>            例: GXS_MARK.P18 / GXS_MARK.SHARED_04
 *
 * ⚠️ **長さの上限をここに書かない。**
 * 伏字が `[A-Za-z0-9_-]{24,}` を `<token>` へ潰すので、長い1語にすると
 * 証跡から目印が消えて外から再照合できなくなる（第26回に実測10件）。
 * だがそれは**形の問題ではなく、伏字を通しても残るかという性質**なので、
 * ランナー側で `maskSecrets(marker) === marker` を、検証器側で
 * 「証跡に残った本文に目印が在るか」を、**実際に測って**確かめる。
 * ここに 23 文字などと書くと、その実測の行は外しても落ちない飾りになる。
 *
 * ⚠️ 予約形にする理由: 第25回の目印は「対象ファイルの中で一意な部分文字列」
 * だったので、Node が自動で出す `Expected values to be strictly equal:` の
 * `xpected ` が目印として通った（P18／P19）。**一般的な文言を目印にできない**形にする。
 */
export const MARKER_PREFIX = 'GXS_MARK.';
export const MARKER_RE = /^GXS_MARK\.[A-Z0-9_]{2,}(?:\.[A-Z0-9_]+)*$/;
